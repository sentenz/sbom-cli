"""Render GFM while preserving Python-Markdown's Mkdocstrings directives.

The upstream Sentenz GFM renderer consumes Markdown source before block
processors run. Autogenerated API pages use `::: sbom.*` directives, which
must instead pass through Mkdocstrings' Python-Markdown block processor.
"""

from markdown.extensions import Extension
from sentenz_gfm import GfmSource, GfmTree, serialize_html


class ApiAwareGfmSource(GfmSource):
    """Keep generated API references in the Python-Markdown pipeline."""

    def run(self, lines):
        self.is_reference = any(
            line.lstrip().startswith("::: sbom.")
            or line.strip() == "::: sbom"
            for line in lines
        )
        if self.is_reference:
            return lines
        return super().run(lines)


class ApiAwareGfmTree(GfmTree):
    """Restore the standard inline processor on Mkdocstrings pages."""

    def __init__(self, md, original_inline):
        super().__init__(md)
        self.original_inline = original_inline

    def run(self, root):
        if self.md.preprocessors["sentenz_gfm"].is_reference:
            return self.original_inline.run(root)
        return super().run(root)


class GfmExtension(Extension):
    """Apply the upstream GFM renderer only to non-reference pages."""

    def extendMarkdown(self, md):
        original_inline = md.treeprocessors["inline"]
        md.preprocessors.register(ApiAwareGfmSource(md), "sentenz_gfm", 1000)
        md.treeprocessors.register(
            ApiAwareGfmTree(md, original_inline), "inline", 20
        )
        md.treeprocessors.deregister("prettify")
        md.output_formats = dict.fromkeys(md.output_formats, serialize_html)


def makeExtension(**kwargs):
    """Return the configurable Markdown extension."""
    return GfmExtension(**kwargs)
