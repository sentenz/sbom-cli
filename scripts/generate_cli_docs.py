"""Render docs/cli.md from the same ConfigArgParse parser used by sbom."""

import argparse
from pathlib import Path

import configargparse

from sbom.cli import create_parser

OUTPUT = Path(__file__).resolve().parents[1] / "docs" / "cli.md"


def options(parser: configargparse.ArgParser, *, reads_config: bool) -> list[str]:
    """Render option bindings without parsing arguments or reading user settings."""
    rows = [
        "| Option | Environment | Config key | Default | Description |",
        "| --- | --- | --- | --- | --- |",
    ]
    for action in parser._actions:
        if not action.option_strings or action.help == argparse.SUPPRESS:
            continue
        flags = ", ".join(f"`{flag}`" for flag in action.option_strings)
        env = getattr(action, "env_var", None)
        keys = parser.get_possible_config_keys(action) if reads_config else []
        default = "—"
        if action.required:
            default = "Required"
        elif action.default is not None and action.default != argparse.SUPPRESS:
            value = action.default
            if isinstance(value, bool):
                value = str(value).lower()
            default = f"`{value}`"
        description = (action.help or "").replace("|", r"\|")
        env_cell = f"`{env}`" if env else "—"
        key_cell = f"`{keys[0]}`" if keys else "—"
        rows.append(f"| {flags} | {env_cell} | {key_cell} | {default} | {description} |")
    return rows


def render() -> str:
    """Generate a reference for the root parser and each registered command."""
    parser = create_parser()
    sections = [
        "<!-- Generated by scripts/generate_cli_docs.py. Edit parser help in src/sbom/cli.py. -->",
        "# CLI reference",
        "",
        "Place root options before the command and command options after it.",
        "Required values can come from any source listed for the option.",
        "A dash means there is no binding or default in that column.",
        "See [configuration precedence](order-of-precedence.md) for resolution rules.",
        "",
        f"## `{parser.prog}`",
        "",
        *options(parser, reads_config=False),
    ]
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for command in action.choices.values():
                sections.extend(["", f"## `{command.prog}`", ""])
                sections.extend(options(command, reads_config=True))
    return "\n".join(sections) + "\n"


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8")
